#!/usr/bin/env python3
"""
Main paper figure for Experiment 2: sequential multi-event robustness.

Expected input:
    raw.csv generated by experiment2_multievent_final.py

Main figure:
    (a) Worst-event resilience vs mean squared control effort across beta.
    (b) Resilience across temporal event position at a representative beta.

The script intentionally keeps the main-paper story compact:
    - robustness to the worst disruption in the sequence,
    - degradation (or preservation) across successive events.

Phase-error Top-k is not used.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


# ---------------------------------------------------------------------
# Style
# ---------------------------------------------------------------------

mpl.rcParams["pdf.fonttype"] = 42
mpl.rcParams["ps.fonttype"] = 42
mpl.rcParams["font.family"] = "DejaVu Serif"
mpl.rcParams["font.serif"] = ["Times New Roman", "DejaVu Serif"]
mpl.rcParams["axes.linewidth"] = 0.9
mpl.rcParams["xtick.major.width"] = 0.8
mpl.rcParams["ytick.major.width"] = 0.8
mpl.rcParams["legend.frameon"] = False


METHODS = [
    "nrpc_gl",
    "nrpc_local",
    "random",
    "betweenness",
    "full",
    "uncontrolled",
]

METHOD_LABELS = {
    "nrpc_gl": "NRPC-GL",
    "nrpc_local": "NRPC-L",
    "random": r"Random-$k$",
    "betweenness": r"Betweenness-$k$",
    "full": "Full consensus",
    "uncontrolled": "Uncontrolled",
}

METHOD_STYLE = {
    "nrpc_gl": dict(
        marker="o",
        linestyle="-",
        linewidth=2.2,
        markersize=8.5,
        zorder=7,
    ),
    "nrpc_local": dict(
        marker="^",
        linestyle="-",
        linewidth=2.0,
        markersize=8.5,
        zorder=6,
    ),
    "random": dict(
        marker="*",
        linestyle="--",
        linewidth=1.3,
        markersize=10.0,
        zorder=4,
    ),
    "betweenness": dict(
        marker="d",
        linestyle="--",
        linewidth=1.3,
        markersize=7.2,
        zorder=3,
    ),
    "full": dict(
        marker="s",
        linestyle="--",
        linewidth=1.6,
        markersize=7.5,
        zorder=5,
    ),
    "uncontrolled": dict(
        marker="X",
        linestyle="none",
        linewidth=0.0,
        markersize=8.5,
        zorder=8,
    ),
}


def sem(x):
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]

    if len(x) <= 1:
        return 0.0

    return float(
        np.std(
            x,
            ddof=1,
        )
        /
        np.sqrt(
            len(x)
        )
    )


def latest_raw(root: Path) -> Path:

    candidates = sorted(
        root.glob(
            "results/experiment2/final*/raw.csv"
        ),
        key=lambda p: p.stat().st_mtime,
    )

    if not candidates:

        candidates = sorted(
            root.glob(
                "results/experiment2/*/raw.csv"
            ),
            key=lambda p: p.stat().st_mtime,
        )

    if not candidates:

        raise FileNotFoundError(
            "No raw.csv found under results/experiment2/. "
            "Pass --raw explicitly."
        )

    return candidates[-1]


def save_both(
    fig,
    outbase: Path,
):

    fig.savefig(
        outbase.with_suffix(
            ".pdf"
        ),
        bbox_inches="tight",
    )

    fig.savefig(
        outbase.with_suffix(
            ".png"
        ),
        dpi=300,
        bbox_inches="tight",
    )

    print(
        f"[saved] "
        f"{outbase.with_suffix('.pdf')}"
    )

    print(
        f"[saved] "
        f"{outbase.with_suffix('.png')}"
    )


def format_axis(
    ax,
    xlabel=None,
    ylabel=None,
    title=None,
):

    if xlabel is not None:

        ax.set_xlabel(
            xlabel,
            fontsize=15,
            fontweight="bold",
        )

    if ylabel is not None:

        ax.set_ylabel(
            ylabel,
            fontsize=16,
            fontweight="bold",
        )

    if title is not None:

        ax.set_title(
            title,
            fontsize=13.5,
            fontweight="bold",
            pad=9,
        )

    ax.tick_params(
        axis="both",
        labelsize=11.5,
    )

    ax.grid(
        alpha=0.18,
        linewidth=0.8,
    )


def tradeoff_panel(
    ax,
    df,
):
    """
    Panel (a): worst-event resilience vs protocol control effort.
    Each non-uncontrolled point corresponds to one beta value.
    """

    summary = (
        df.groupby(
            [
                "beta",
                "method",
            ],
            as_index=False,
        )
        .agg(
            energy_mean=(
                "energy",
                "mean",
            ),
            energy_std=(
                "energy",
                "std",
            ),
            worst_mean=(
                "resilience_worst",
                "mean",
            ),
            worst_std=(
                "resilience_worst",
                "std",
            ),
        )
    )

    positive_energy = summary.loc[
        summary[
            "energy_mean"
        ]
        >
        0,
        "energy_mean",
    ]

    linthresh = max(
        float(
            positive_energy.min()
        )
        /
        4.0,
        1e-5,
    )

    for method in METHODS:

        d = (
            summary[
                summary[
                    "method"
                ]
                ==
                method
            ]
            .sort_values(
                "beta"
            )
        )

        if d.empty:

            continue

        style = METHOD_STYLE[
            method
        ]

        if method == "uncontrolled":

            row = d.iloc[0]

            ax.plot(
                row[
                    "energy_mean"
                ],
                row[
                    "worst_mean"
                ],
                marker=style[
                    "marker"
                ],
                linestyle="none",
                markersize=10,
                label=METHOD_LABELS[
                    method
                ],
                zorder=style[
                    "zorder"
                ],
                markeredgecolor="black",
                markeredgewidth=0.5,
            )

            continue

        x = d[
            "energy_mean"
        ].to_numpy()

        y = d[
            "worst_mean"
        ].to_numpy()

        y_std = (
            d[
                "worst_std"
            ]
            .fillna(
                0.0
            )
            .to_numpy()
        )

        ax.plot(
            x,
            y,
            marker=style[
                "marker"
            ],
            linestyle=style[
                "linestyle"
            ],
            linewidth=style[
                "linewidth"
            ],
            markersize=style[
                "markersize"
            ],
            label=METHOD_LABELS[
                method
            ],
            zorder=style[
                "zorder"
            ],
            markeredgecolor="black",
            markeredgewidth=0.45,
        )

        # Light variability bands for the main adaptive/full methods.
        if method in {
            "nrpc_gl",
            "nrpc_local",
            "full",
        }:

            ax.fill_between(
                x,
                y
                -
                y_std,
                y
                +
                y_std,
                alpha=0.07,
                linewidth=0,
                zorder=max(
                    style[
                        "zorder"
                    ]
                    -
                    1,
                    0,
                ),
            )

    ax.set_xscale(
        "symlog",
        linthresh=linthresh,
        linscale=0.8,
    )

    ax.set_xticks([1e-4, 1e-3, 1e-2, 1e-1, 1e0])

    format_axis(
        ax,
        xlabel=(
            r"Mean Squared Control Effort "
            r"$\mathbb{E}[u^2]$"
        ),
        ylabel=(
            r"Worst-Event Resilience "
            r"$\rho_{\rm worst}$"
        ),
        title=(
            "(a) Multi-event robustness–effort trade-off"
        ),
    )

    ax.text(
        0.3,
        0.85,
        "Sparse controllers:\n" + r"$10\%$ active nodes",
        transform=ax.transAxes,
        ha="center",
        va="top",
        fontsize=10.0,
        bbox=dict(
            boxstyle="round,pad=0.25",
            facecolor="cyan",
            alpha=0.08,
            edgecolor="gray",
        ),
    )


def event_position_panel(
    ax,
    df,
    beta_for_position,
):
    """
    Panel (b): resilience by event position for one representative beta.
    """

    sub = df[
        np.isclose(
            df[
                "beta"
            ].astype(
                float
            ),
            beta_for_position,
        )
    ].copy()

    if sub.empty:

        raise ValueError(
            f"No rows found for beta="
            f"{beta_for_position:g}"
        )

    event_columns = [
        "event1_resilience",
        "event2_resilience",
        "event3_resilience",
    ]

    x = np.array(
        [
            1,
            2,
            3,
        ]
    )

    for method in METHODS:

        d = sub[
            sub[
                "method"
            ]
            ==
            method
        ]

        if d.empty:

            continue

        means = np.array(
            [
                d[
                    col
                ].mean()
                for col
                in event_columns
            ],
            dtype=float,
        )

        sems = np.array(
            [
                sem(
                    d[
                        col
                    ]
                )
                for col
                in event_columns
            ],
            dtype=float,
        )

        style = METHOD_STYLE[
            method
        ]

        if method == "uncontrolled":

            linestyle = ":"
            linewidth = 1.3

        else:

            linestyle = style[
                "linestyle"
            ]

            linewidth = style[
                "linewidth"
            ]

        ax.errorbar(
            x,
            means,
            yerr=sems,
            marker=style[
                "marker"
            ],
            linestyle=linestyle,
            linewidth=linewidth,
            markersize=style[
                "markersize"
            ],
            capsize=3.0,
            label=METHOD_LABELS[
                method
            ],
            zorder=style[
                "zorder"
            ],
            markeredgecolor="black",
            markeredgewidth=0.45,
        )

    format_axis(
        ax,
        xlabel="Event position in the sequence",
        ylabel="Event Resilience",
        title=(
            rf"(b) Sequential robustness at "
            rf"$\beta={beta_for_position:g}$"
        ),
    )

    ax.set_xticks(
        [
            1,
            2,
            3,
        ],
        [
            "Event 1",
            "Event 2",
            "Event 3",
        ],
    )

    ax.text(
        0.6,
        0.7,
        (
            "Each trajectory contains:\n one Drift, "
            "Pulse, and Cancellation event"
        ),
        transform=ax.transAxes,
        ha="center",
        va="top",
        fontsize=10,
        bbox=dict(
            boxstyle="round,pad=0.25",
            facecolor="cyan",
            alpha=0.08,
            edgecolor="gray",
        ),
    )


def make_event_type_figure(
    df,
    outdir,
    beta_for_position,
):
    """
    Optional diagnostic/supplementary figure:
    resilience by disruption type at one beta.
    """

    sub = df[
        np.isclose(
            df[
                "beta"
            ].astype(
                float
            ),
            beta_for_position,
        )
    ].copy()

    type_columns = {
        "Drift":
            "drift_resilience",

        "Pulse":
            "pulse_resilience",

        "Cancellation":
            "cancel_resilience",
    }

    fig, ax = plt.subplots(
        1,
        1,
        figsize=(
            7.4,
            4.8,
        ),
    )

    x = np.arange(
        len(
            type_columns
        )
    )

    for method in METHODS:

        d = sub[
            sub[
                "method"
            ]
            ==
            method
        ]

        if d.empty:

            continue

        means = np.array(
            [
                d[
                    col
                ].mean()
                for col
                in type_columns.values()
            ]
        )

        sems = np.array(
            [
                sem(
                    d[
                        col
                    ]
                )
                for col
                in type_columns.values()
            ]
        )

        style = METHOD_STYLE[
            method
        ]

        ax.errorbar(
            x,
            means,
            yerr=sems,
            marker=style[
                "marker"
            ],
            linestyle=(
                ":"
                if method
                ==
                "uncontrolled"
                else style[
                    "linestyle"
                ]
            ),
            linewidth=(
                1.3
                if method
                ==
                "uncontrolled"
                else style[
                    "linewidth"
                ]
            ),
            markersize=style[
                "markersize"
            ],
            capsize=3.0,
            label=METHOD_LABELS[
                method
            ],
        )

    ax.set_xticks(
        x,
        list(
            type_columns.keys()
        ),
    )

    format_axis(
        ax,
        xlabel="Disruption type",
        ylabel="Event Resilience",
        title=(
            rf"Multi-event resilience by disruption type "
            rf"($\beta={beta_for_position:g}$)"
        ),
    )

    ax.legend(
        ncol=3,
        fontsize=9.5,
    )

    fig.tight_layout()

    save_both(
        fig,
        outdir
        /
        "fig3_multievent_by_type",
    )

    plt.close(
        fig
    )


def main():

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--raw",
        type=Path,
        default=None,
        help=(
            "Path to Experiment 2 raw.csv. "
            "If omitted, latest final run is used."
        ),
    )

    parser.add_argument(
        "--outdir",
        type=Path,
        default=Path(
            "figures/experiment2"
        ),
    )

    parser.add_argument(
        "--position-beta",
        type=float,
        default=5.0,
        help=(
            "Representative beta used in the "
            "event-position panel."
        ),
    )

    args = parser.parse_args()

    root = Path.cwd()

    raw_path = (
        args.raw
        if args.raw is not None
        else latest_raw(
            root
        )
    )

    df = pd.read_csv(
        raw_path
    )

    required = {
        "beta",
        "trial",
        "method",
        "energy",
        "resilience_worst",
        "event1_resilience",
        "event2_resilience",
        "event3_resilience",
        "drift_resilience",
        "pulse_resilience",
        "cancel_resilience",
    }

    missing = sorted(
        required
        -
        set(
            df.columns
        )
    )

    if missing:

        raise ValueError(
            f"Missing required columns "
            f"in raw.csv: {missing}"
        )

    args.outdir.mkdir(
        parents=True,
        exist_ok=True,
    )

    print(
        f"[input] {raw_path}"
    )

    print(
        f"[output] {args.outdir}"
    )

    # ---------------------------------------------------------
    # Main 2-panel paper figure.
    # ---------------------------------------------------------

    fig, axes = plt.subplots(
        1,
        2,
        figsize=(
            14.8,
            5.35,
        ),
    )

    tradeoff_panel(
        axes[0],
        df,
    )

    event_position_panel(
        axes[1],
        df,
        beta_for_position=args.position_beta,
    )

    # Shared legend
    handles = []
    labels = []

    for ax in axes:

        h, l = (
            ax.get_legend_handles_labels()
        )

        for hh, ll in zip(
            h,
            l,
        ):

            if ll not in labels:

                handles.append(
                    hh
                )

                labels.append(
                    ll
                )

    fig.legend(
        handles,
        labels,
        loc="lower center",
        bbox_to_anchor=(
            0.5,
            -0.025,
        ),
        ncol=3,
        fontsize=11.0,
        framealpha=0.9,
    )

    # fig.suptitle(
    #     "Sequential Multi-Event Robustness",
    #     fontsize=15,
    #     fontweight="bold",
    #     y=0.985,
    # )

    fig.subplots_adjust(
        left=0.075,
        right=0.99,
        top=0.88,
        bottom=0.22,
        wspace=0.24,
    )

    save_both(
        fig,
        args.outdir
        /
        "fig3_multievent_main",
    )

    plt.close(
        fig
    )

    # ---------------------------------------------------------
    # Secondary diagnostic figure. Useful if temporal position
    # and perturbation type need to be disentangled in the paper
    # or supplementary material.
    # ---------------------------------------------------------

    make_event_type_figure(
        df,
        args.outdir,
        beta_for_position=args.position_beta,
    )


if __name__ == "__main__":
    main()
