SCENARIOS = ["drift", "pulse", "cancel"]
SCENARIO_LABELS = {
    "drift": "Frequency drift",
    "pulse": "Transient pulse",
    "cancel": "Dynamics cancellation",
}

METHOD_LABELS = {
    "nrpc_gl": "NRPC-GL",
    "nrpc_local": "NRPC-L",
    "full": "Full consensus",
    "random": r"Random-$k$",
    "phase": r"Phase-error Top-$k$",
    "betweenness": r"Betweenness-$k$",
    "uncontrolled": "Uncontrolled",
}

METHOD_STYLE = {
    "nrpc_gl": dict(marker="o", linestyle="-", linewidth=1.8, markersize=5.5, zorder=7),
    "nrpc_local": dict(marker="^", linestyle="-", linewidth=1.6, markersize=5.5, zorder=6),
    "full": dict(marker="s", linestyle="--", linewidth=1.3, markersize=5.0, zorder=5),
    "random": dict(marker="*", linestyle="--", linewidth=1.1, markersize=7.0, zorder=3),
    "phase": dict(marker="P", linestyle="--", linewidth=1.1, markersize=5.0, zorder=4),
    "betweenness": dict(marker="d", linestyle="--", linewidth=1.1, markersize=4.8, zorder=2),
    "uncontrolled": dict(marker="X", linestyle="none", markersize=5.2, zorder=8),
}


def latest_raw(root: Path) -> Path:
    candidates = sorted(
        root.glob("results/experiment1/final*/raw.csv"),
        key=lambda p: p.stat().st_mtime,
    )
    if not candidates:
        candidates = sorted(
            root.glob("results/experiment1/*/raw.csv"),
            key=lambda p: p.stat().st_mtime,
        )
    if not candidates:
        raise FileNotFoundError(
            "No raw.csv found under results/experiment1/. "
            "Pass --raw explicitly."
        )
    return candidates[-1]


def latest_pkl(root: Path) -> Path:
    candidates = sorted(
        root.glob("results/experiment1/final*/results.pkl"),
        key=lambda p: p.stat().st_mtime,
    )
    if not candidates:
        candidates = sorted(
            root.glob("results/experiment1/*/results.pkl"),
            key=lambda p: p.stat().st_mtime,
        )
    if not candidates:
        raise FileNotFoundError(
            "No results.pkl found under results/experiment1/. "
            "Pass --pkl explicitly."
        )
    return candidates[-1]


def sem(x):
    x = np.asarray(x, dtype=float)
    x = x[np.isfinite(x)]
    if len(x) <= 1:
        return 0.0
    return float(np.std(x, ddof=1) / np.sqrt(len(x)))


def grouped_mean_sem(df, group_cols, value_col):
    out = (
        df.groupby(group_cols, as_index=False)[value_col]
        .agg(["mean", sem])
        .reset_index()
        .rename(columns={"sem": "sem"})
    )
    return out


def save_both(fig, outbase: Path):
    fig.savefig(outbase.with_suffix(".pdf"), bbox_inches="tight")
    fig.savefig(outbase.with_suffix(".png"), dpi=300, bbox_inches="tight")
    print(f"[saved] {outbase.with_suffix('.pdf')}")
    print(f"[saved] {outbase.with_suffix('.png')}")


def format_axis(ax, xlabel=None, title=None):
    if xlabel is not None:
        ax.set_xlabel(
            xlabel,
            fontsize=16,
            fontweight="bold",
        )

    if title is not None:
        ax.set_title(
            title,
            fontsize=14,
            fontweight="bold",
            pad=10,
        )

    ax.tick_params(
        axis="both",
        labelsize=11.5,
    )

    ax.grid(
        alpha=0.18,
        linewidth=0.8,
    )


def figure1_tradeoff(df: pd.DataFrame, outdir: Path, include_phase=False):
    """
    Resilience vs mean squared control effort.

    This version follows the visual structure of the original NRPC trade-off
    figure: shared y-axis, symlog effort axis, variability bands, large markers,
    and a bottom-centered legend.
    """

    methods = [
        "nrpc_gl",
        "nrpc_local",
        "random",
        "betweenness",
        "full",
        "uncontrolled",
    ]

    if include_phase:
        methods.insert(2, "phase")

    # Build the summary expected by the requested plotting structure.
    summary = (
        df.groupby(
            ["scenario", "beta", "method"],
            as_index=False,
        )
        .agg(
            energy_mean=("energy", "mean"),
            energy_std=("energy", "std"),
            resilience_mean=("resilience", "mean"),
            resilience_std=("resilience", "std"),
        )
    )

    fig, axes = plt.subplots(
        1,
        3,
        figsize=(16.5, 5.4),
        sharey=True,
    )

    # Positive effort values define the symlog transition.
    positive_energy = summary.loc[
        summary["energy_mean"] > 0,
        "energy_mean",
    ]

    linthresh = max(
        float(positive_energy.min()) / 4.0,
        1e-5,
    )

    for ax, scenario in zip(axes, SCENARIOS):
        sub = summary[
            summary["scenario"] == scenario
        ]

        for method in methods:
            d = (
                sub[sub["method"] == method]
                .sort_values("beta")
            )

            if len(d) == 0:
                continue

            style = METHOD_STYLE[method]

            # Uncontrolled has exactly zero effort and therefore is shown once.
            if method == "uncontrolled":
                row = d.iloc[0]

                ax.plot(
                    row["energy_mean"],
                    row["resilience_mean"],
                    marker=style["marker"],
                    linestyle=style["linestyle"],
                    markersize=10,
                    label=METHOD_LABELS[method],
                    zorder=style["zorder"],
                    markeredgecolor="black",
                    markeredgewidth=0.6,
                )
                continue

            x = d["energy_mean"].to_numpy()
            y = d["resilience_mean"].to_numpy()
            y_std = (
                d["resilience_std"]
                .fillna(0.0)
                .to_numpy()
            )

            ax.plot(
                x,
                y,
                marker=style["marker"],
                linestyle=style["linestyle"],
                markersize=9,
                linewidth=2.2,
                label=METHOD_LABELS[method],
                zorder=style["zorder"],
                markeredgecolor="black",
                markeredgewidth=0.5,
            )

            # Variability bands, following the visual language of the
            # original NRPC trade-off figure. We keep the static
            # betweenness band off because it can visually dominate.
            if method not in {"betweenness", "phase"}:
                ax.fill_between(
                    x,
                    y - y_std,
                    y + y_std,
                    alpha=0.08,
                    linewidth=0,
                    zorder=max(
                        style["zorder"] - 1,
                        0,
                    ),
                )

        # symlog keeps the zero-effort uncontrolled point while retaining
        # log-like separation among positive effort values.
        ax.set_xscale(
            "symlog",
            linthresh=linthresh,
            linscale=0.8,
        )

        format_axis(
            ax,
            xlabel=r"Mean Squared Control Effort $\mathbb{E}[u^2]$",
            title=SCENARIO_LABELS[scenario],
        )

        ax.set_ylim(
            0.50,
            1.01,
        )

        # Light annotation matching the original paper style.
        ax.text(
            0.35,
            0.92,
            r"Sparse controllers: $10\%$ active nodes",
            transform=ax.transAxes,
            ha="center",
            va="top",
            fontsize=10.5,
            bbox=dict(
                boxstyle="round,pad=0.25",
                facecolor="cyan",
                alpha=0.08,
                edgecolor="gray",
            ),
        )

    axes[0].set_ylabel(
        r"Resilience $\rho$",
        fontsize=18,
        fontweight="bold",
    )

    handles, labels = axes[-1].get_legend_handles_labels()
    unique = dict(
        zip(
            labels,
            handles,
        )
    )

    fig.legend(
        unique.values(),
        unique.keys(),
        fontsize=11.5,
        loc="lower center",
        bbox_to_anchor=(0.5, -0.035),
        ncol=3 if not include_phase else 4,
        framealpha=0.9,
    )

    fig.subplots_adjust(
        left=0.065,
        right=0.99,
        top=0.91,
        bottom=0.22,
        wspace=0.16,
    )

    save_both(
        fig,
        outdir / "fig1_tradeoff",
    )

    plt.close(fig)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--raw",
        type=Path,
        default=None,
        help="Path to Experiment 1 raw.csv. If omitted, latest run is used.",
    )
    parser.add_argument(
        "--pkl",
        type=Path,
        default=None,
        help="Path to Experiment 1 results.pkl. If omitted, latest run is used.",
    )
    parser.add_argument(
        "--outdir",
        type=Path,
        default=Path("figures/experiment1"),
    )
    args = parser.parse_args()

    root = Path.cwd()
    raw_path = args.raw if args.raw is not None else latest_raw(root)
    pkl_path = args.pkl if args.pkl is not None else latest_pkl(root)

    df = pd.read_csv(raw_path)

    required = {
        "scenario",
        "beta",
        "trial",
        "method",
        "resilience",
        "energy",
        "gamma_rec_mean",
    }
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(f"Missing required columns in raw.csv: {missing}")

    args.outdir.mkdir(parents=True, exist_ok=True)

    print(f"[input raw] {raw_path}")
    print(f"[input pkl] {pkl_path}")
    print(f"[output] {args.outdir}")

    figure1_tradeoff(df, args.outdir, include_phase=False)


if __name__ == "__main__":
    main()
